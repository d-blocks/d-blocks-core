# Integration Tests Package
#
# This package contains integration tests that test the interaction between
# multiple components of the d-blocks-core system. These tests may:
#
# - Use real databases
# - Perform actual file I/O operations  
# - Test end-to-end workflows
# - Require external dependencies
# - Take longer to execute
#
# These tests are marked with @pytest.mark.integration and are typically
# run as part of the full test suite before production releases.
